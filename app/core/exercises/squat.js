// 資料來源：UI-PRMD（Vakanski, Jun, Paul & Baker, Data 2018, 3(1):2），
//   授權 ODC-PDDL v1.0（公眾領域）。10 位健康受試者 × 每人 10 次 deep squat，
//   correct 與 incorrect 各一組。採用 **Vicon** 光學動捕的絕對座標（39 個標記點，100Hz）。
//   （不採 Kinect：其 positions 為相對父關節的偏移、需配合角度做 FK 還原，
//     而作者在 Animation.m 自述「下肢關節重建不完全正確」；實測亦證實 ——
//     深蹲時雙腳踩地，重建出的踝距卻在一次動作內從 2.7 擺盪到 113。Vicon 版同一量
//     變異係數僅 0.019。詳見 docs/verification/UI-PRMD_門檻標定.md）
//
// 標定方法：把 Vicon 的 3D 座標以真實筆電機位（鏡頭高 1150mm、距離 1.6 倍身高）
//   做透視投影成正面影像座標 → 降頻至 30Hz → 餵入本專案引擎，
//   量測條件與程式實際判定條件完全一致（同樣的 progress 閘門、同樣的 scale）。
//
// ⚠️ 三個必須一併記住的限制：
//   1. UI-PRMD 的 deep squat 是 FMS 版本（雙臂過頭持棒），比本 App 的徒手深蹲更深、
//      前傾更多。門檻由此標定偏保守，真人測試時須複核。
//   2. incorrect 組原文為「arbitrarily in a suboptimal manner」，**未標註錯誤型別**。
//      故「不正確組觸發率」只代表趨勢，**不等於對該項錯誤的偵測率**，不得如此對外描述。
//   3. 只有「誤判率」是標定過的（取正確組第 5 百分位）；靈敏度全部未標定。
//   4. ⚠️ FMS deep squat 是**雙臂過頭**做的，肩胛上旋使肩峰標記內移 ——
//      實測 10 位受試者的肩寬平均僅 226mm（身高約 1.55m），明顯低於成人正常值。
//      因此**凡是以肩寬正規化的量，在本資料集上都被系統性放大**（約 1.5 倍）。
//      knee / head_tilt 兩項皆屬此類，其分位數不可直接當成本 App 的門檻。
//      torso_lean 不受影響（它是同一個量的前後比值，肩寬不進入計算）。
//
// 【2026-08-30 交叉驗證】另以 REHAB24-6（Černek et al., 2024，Zenodo，
//   DOI 10.5281/zenodo.13305826，授權 CC BY-NC 4.0）的 Ex6 深蹲獨立複核
//   （89 次正確 + 41 次不正確，物理治療師標註，肩寬 357mm 為正常值）：
//     · 軀幹投影比 0.58 → 誤判 3.6%    ✅ 確認
//     · 頭偏移      0.18 → 誤判 0.0%    ✅ 確認
//     · 髖高差      0.10 → 兩組皆 0.0%  ⛔ 完全不觸發 → 該判定已移除（理由見下方說明）
//     · 膝距/肩寬   1.70 → 誤判 32.7%   ❌ 推翻，已下修為 1.50
//   ⚠️ 該資料集的深蹲為復健用的部分範圍（130 次中無一次髖低於膝），驗證不了深度判準。
// ══════════════════════════════════════════════════════════════════════════

// 膝距（左右膝水平距離）÷ 肩寬 的下限。低於此值＝雙膝過度靠攏（正面觀的膝內夾特徵）。
//
// ── 標定歷程（兩個獨立資料集，勿逕行改動）──
// UI-PRMD（筆電機位）：正確組 p05=2.58、中位 3.38。但該資料集因雙臂過頭而低估肩寬
//   （實測 226mm），凡以肩寬為分母者皆被系統性放大，其分位數不可直接採用。
// REHAB24-6 Ex6 深蹲（2026-08-30 交叉驗證）：**肩寬 357mm，未受過頭姿勢壓縮**，
//   為本項更可靠的標定來源。正確組 p01=1.489、p05=1.514、中位 1.852（n=52 幀）。
//   兩者換算後一致：2.58 ÷ (357/226) ≈ 1.63，與 1.51 同一量級。
// ⚠️ 前一版取 1.70，經 REHAB24-6 交叉驗證在**正確**動作上誤判 32.7%，已下修。
// 1.50 取 REHAB24-6 正確組 p05 附近；該資料集實測誤判 3.8%。
// ⚠️ 靈敏度依然未標定：此門檻對「不正確」樣本的觸發率僅 6.9%，而兩個資料集都沒有
//   標註過的膝內夾樣本 —— 本項的偵測能力目前無任何證據支持。維持 advisory 即基於此。
export const KNEE_SPAN_MIN_RATIO = 1.50;

// 軀幹前傾門檻：軀幹畫面投影長 ÷ 站立基準。低於此值判為彎腰代償。
// ⚠️ 前一版為 0.86，依透視模型「試算」而來，未經任何真人驗證。實測證明不可用：
//    在真實筆電機位下，它在**正確**深蹲上誤判 90.8% 的幀。
// ⚠️ 更根本的問題：這個量對鏡頭高度不具不變性。同一次正確深蹲的最小值為
//    地板 0.892 ／ 800mm 0.751 ／ 1150mm 0.686 ／ 1500mm 0.618 ——
//    人蹲下去時俯角變大，軀幹投影本來就縮短，與前傾與否無關。
// 0.58 的由來：取正確組在筆電機位的 p05（0.587），且低於最不利機位（1500mm）
//    正常深蹲的最小值 0.618，故在各種合理機位下都不會誤判正常深蹲。
//    代價是靈敏度下降（不正確組觸發率 37.7%）。
export const TORSO_FOLD_RATIO = 0.58;

// 頭部側傾門檻：鼻相對肩中心的水平偏移 ÷ 肩寬。BSA ①「頭部位置」。
// ⚠️ 只測得到「側傾」——頭部前傾屬矢狀面，正面投影無水平位移，與 torso_lean 同類限制。
// 實測（筆電機位）：正確組誤判 0.0%，不正確組觸發 18.8%。四項中鑑別趨勢最明確者。
// 維持 0.18 未收緊（收到 0.115 可把觸發率提到 26.2%）：一來避免過度擬合單一資料集，
// 二來該實測同樣受限制 4 污染 —— 修正肩寬偏誤後正確組 p95 約 0.05，0.18 仍在安全側。
export const HEAD_TILT_RATIO = 0.18;

